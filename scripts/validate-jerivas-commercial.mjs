import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
const route="/empreendimentos/jerivas-caminhos-da-lapa/";
const url="https://www.moretegra.com.br"+route;
const html=read("src-greenn/empreendimentos/jerivas-caminhos-da-lapa/index.html");
const css=read("src-greenn/empreendimentos/jerivas-caminhos-da-lapa/jerivas.css");
const config=JSON.parse(read("vercel.json"));
const sitemap=read("sitemap.xml");
const blog=read("src-greenn/blog/mercado/lapa-o-novo-polo-de-valorizacao-na-zona-oeste-de-sao-paulo/index.html");
const urban=read("src-greenn/blog/bairros-sao-paulo/lapa-vila-anastacio-como-escolher/index.html");
assert.deepEqual(config.rewrites.filter(x=>x.source===route),[{source:route,destination:"/src-greenn/empreendimentos/jerivas-caminhos-da-lapa/index.html"}]);
assert.ok(sitemap.includes("<loc>"+url+"</loc>"));
assert.ok(html.includes('rel="canonical" href="'+url+'"'));
assert.ok(html.includes('name="robots" content="index,follow,max-image-preview:large"'));
assert.equal((html.match(/<h1\b/g)||[]).length,1);
assert.ok(html.includes("Jerivás Caminhos da Lapa"));
assert.ok(html.includes("preço")&&html.includes("valores")&&html.includes("disponibilidade"));
assert.ok(html.includes("105 e 136 m²")&&html.includes("3 ou 4")&&html.includes("2 ou 3"));
assert.ok(html.includes("venda original")&&html.includes("encerrada"));
assert.ok(!/R\$\s*\d/.test(html),"unverified prices forbidden");
assert.ok(!html.includes('"@type":"Offer"'),"no offer without verified inventory");
assert.ok(!html.includes('"availability":"https://schema.org/InStock"'));
assert.ok(!html.includes('content="noindex'));
for(const p of ["/favicon.ico","/favicon-16x16.png","/favicon-32x32.png","/favicon-48x48.png","/apple-touch-icon.png"])assert.ok(html.includes('href="'+p+'"'),"favicon missing "+p);
const pics=[...html.matchAll(/<img\b[^>]*>/g)].map(x=>x[0]);
assert.ok(pics.length>=7);
const hero=pics.find(x=>x.includes('class="hero-image"'));
assert.ok(hero&&hero.includes('fetchpriority="high"')&&!hero.includes('loading="lazy"'));
for(const pic of pics)assert.ok(/\balt="[^"]*"/.test(pic)&&/\bsrc="[^"]+"/.test(pic),"alt and src required");
assert.ok(pics.filter(x=>x.includes('loading="lazy"')).length>=5);
const graph=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])["@graph"];
const node=t=>graph.find(x=>x["@type"]===t);
for(const t of ["WebSite","WebPage","BreadcrumbList","ImageObject","ApartmentComplex","FloorPlan","Person","ContactPoint","RealEstateAgent","FAQPage"])assert.ok(node(t),"missing Schema.org node "+t);
assert.equal(graph.filter(x=>x["@type"]==="FloorPlan").length,2);
assert.equal(node("WebPage").url,url);
assert.equal(node("ApartmentComplex").url,url);
assert.equal(node("RealEstateAgent").telephone,"+5511960779328");
assert.equal(node("Person").identifier.value,"209.905-F");
assert.equal(node("FAQPage").mainEntity.length,5);
assert.equal((html.match(/<details>/g)||[]).length,5,"visible FAQ count");
for(const q of node("FAQPage").mainEntity){assert.ok(html.includes("<summary>"+q.name+"</summary>"));assert.ok(html.includes("<p>"+q.acceptedAnswer.text+"</p>"));}
assert.ok(html.includes('data-moretegra-lead-form data-form-id="46"'));
assert.ok(html.includes('name="tenant_id" value="313"')&&html.includes('name="form_id" value="46"'));
assert.ok(html.includes('name="title" value="MoreEmUmTegra"'));
for(const id of ["mt-lead-intent","mt-lead-name","mt-lead-email","mt-phone-country","mt-lead-phone","mt-lead-error","mt-lead-status"])assert.ok(html.includes('id="'+id+'"'));
for(const script of ["runtime.js","measurement-core.js","measurement-form.js"])assert.ok(html.includes("/src-greenn/preview/"+script));
assert.ok(html.includes('data-mnt-page-identity="jerivas_caminhos_da_lapa_project"'));
assert.ok(html.includes('href="https://www.caminhosdalapategra.com.br/jerivas/"'),"history owner linked");
for(const page of [blog,urban])assert.ok(page.includes('href="'+route+'"'),"blog commercial link missing");
assert.ok(css.includes("grid-template-columns:1fr")&&css.includes(".floating"));
console.log(JSON.stringify({pass:true,page:url,schemaNodes:graph.length,faq:5,pics:pics.length,formId:46,commercialLinks:2}));
