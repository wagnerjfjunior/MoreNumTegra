import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const path='src-greenn/empreendimentos/ampere-brooklin/index.html';
const html=readFileSync(path,'utf8');
const match=html.match(/<script\b(?=[^>]*type=["']application\/ld\+json["'])[^>]*>([\s\S]*?)<\/script>/i);
assert(match,'Ampère JSON-LD script must exist');
const graph=JSON.parse(match[1])['@graph'];
assert.equal(graph.length,18,'Ampère canonical graph has 18 factual nodes');
const get=t=>graph.filter(x=>x['@type']===t);
const one=t=>{assert.equal(get(t).length,1,'exactly one '+t);return get(t)[0]};
const base='https://www.moretegra.com.br/empreendimentos/ampere-brooklin/';
const project=one('ApartmentComplex'),page=one('WebPage'),product=one('Product'),offer=one('Offer'),brand=one('Brand'),org=one('Organization'),person=one('Person'),agent=one('RealEstateAgent'),service=one('Service');
for(const t of ['WebSite','BreadcrumbList','FAQPage','ContactPoint'])one(t);
assert.equal(get('ImageObject').length,2);
assert.equal(get('FloorPlan').length,3);
assert.equal(project['@id'],base+'#project');
assert.equal(project.brand,undefined,'ApartmentComplex.brand forbidden by Schema.org');
assert.equal(project.address.streetAddress,'Rua André Ampére, 136');
assert.equal(project.address.postalCode,'04562-080');
assert.deepEqual(agent.address,project.address,'Agent works on site at project address');
assert.equal(person.identifier?.value,'209.905-F');
assert.equal(agent.identifier?.value,'209.905-F');
assert.equal(brand.name,'Tegra');
assert.equal(org.brand?.['@id'],brand['@id']);
assert.equal(product.brand?.['@id'],brand['@id']);
assert.equal(product.isRelatedTo?.['@id'],project['@id']);
assert.equal(product.offers?.['@id'],offer['@id']);
assert.equal(offer.itemOffered?.['@id'],product['@id']);
assert.equal(offer.priceCurrency,'BRL');
assert.equal(offer.price,'3990700.00');
assert.equal(offer['@id'],base+'#offer-62');
assert.equal(product['@id'],base+'#product-62');
assert(!Object.hasOwn(offer,'availability'),'Never fabricate stock');
assert(!Object.hasOwn(product,'aggregateRating'),'Never fabricate ratings');
assert(!Object.hasOwn(product,'review'),'Never fabricate reviews');
assert(html.includes('Condições comerciais · unidade 62')&&html.includes('id="mnt-condition-price">R$ 3.990.700')&&html.includes('Unidade 62 · condição promocional de referência R$ 3.990.700'),'Visible reference and unit must match offer');
assert(html.includes('R$ 3.791.165 à vista*')&&html.includes('data-mnt-condition="avista"'),'Approved cash condition must remain available');
assert(service.provider?.['@id']===org['@id']&&service.broker?.['@id']===person['@id']);
assert(page.mainEntity?.['@id']===project['@id']);
assert.equal(project.accommodationFloorPlan.length,3);
const officialImages=[...html.matchAll(/const plants=(\[\[.*?\]\]);const pTabs=/gs)].map(m=>JSON.parse(m[1])).flat();
assert.equal(officialImages.length,3);
const floors=get('FloorPlan');
const ids=new Map(graph.filter(x=>x['@id']).map(x=>[x['@id'],x]));
assert.equal(ids.size,graph.length,'all graph nodes have unique ids');
for(let i=0;i<floors.length;i++){
 assert.equal(floors[i].image,officialImages[i][3],'Official floor plan must match selector');
 assert.equal(floors[i].floorSize?.value,262);
 assert.equal(floors[i].floorSize?.unitCode,'MTK');
 assert(ids.has(project.accommodationFloorPlan[i]['@id']));
}
const projImages=project.image;
assert(Array.isArray(projImages)&&projImages.length>=2);
assert.equal(new Set(projImages).size,projImages.length);
assert(page.image?.every(x=>ids.has(x['@id'])),'page image references must resolve');
for(const key of ['offers','isRelatedTo'])assert(ids.has(product[key]['@id']));
for(const key of ['worksFor','workLocation'])assert(ids.has(person[key]['@id']));
assert.equal(project.url,base);
console.log('AMPERE_SCHEMA_PARITY_PASS nodes=18 plans=3 facts=GOVERNED brand=COMPATIBLE jsonld_only=true');
