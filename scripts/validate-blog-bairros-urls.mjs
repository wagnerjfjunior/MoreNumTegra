import assert from "node:assert/strict";
import {readFileSync,existsSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
const cat="/blog/bairros-sao-paulo/";
const old="/blog/mercado/lapa-o-novo-polo-de-valorizacao-na-zona-oeste-de-sao-paulo/";
const updated="/blog/mercado/valorizacao-imobiliaria-lapa-sao-paulo/";
const article="/blog/bairros-sao-paulo/lapa-vila-anastacio-como-escolher/";
const host="https://www.moretegra.com.br";
const v=JSON.parse(read("vercel.json"));
const rew=x=>v.rewrites.filter(r=>r.source===x);
assert.deepEqual(rew(cat),[{source:cat,destination:"/src-greenn/blog/bairros-sao-paulo/index.html"}],"category is a live route");
assert.deepEqual(rew(updated),[{source:updated,destination:"/src-greenn/blog/mercado/valorizacao-imobiliaria-lapa-sao-paulo/index.html"}],"new market canonical is served");
assert.equal(rew(old).length,0,"old Lapa article must not be rewritten");
assert.deepEqual(v.redirects.filter(r=>r.source===old),[{source:old,destination:updated,permanent:true}],"old Lapa URL must have exactly one 301");
assert.equal(existsSync("src-greenn/blog/mercado/lapa-o-novo-polo-de-valorizacao-na-zona-oeste-de-sao-paulo/index.html"),false,"old source file must be removed");
const xml=read("sitemap.xml");
const urls=[...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map(x=>x[1]);
for(const x of [cat,updated,article])assert.ok(urls.includes(host+x),"missing sitemap URL "+x);
assert.ok(!urls.includes(host+old),"old redirected page must not remain in sitemap");
assert.equal(new Set(urls).size,urls.length,"duplicate sitemap URLs");
const home=read("src-greenn/blog/index.html");
const category=read("src-greenn/blog/bairros-sao-paulo/index.html");
const sibling=read("src-greenn/blog/bairros-sao-paulo/lapa-vila-anastacio-como-escolher/index.html");
const market=read("src-greenn/blog/mercado/valorizacao-imobiliaria-lapa-sao-paulo/index.html");
const index=read("src-greenn/blog/mercado/index.html");
const css=read("src-greenn/blog/bairros-sao-paulo/bairros.css");
assert.ok(home.includes('id="bairros-sao-paulo"')&&home.includes('href="'+cat+'"'),"Bairros must be discoverable on blog homepage");
assert.ok(home.includes('href="#bairros-sao-paulo"'),"Bairros must be reachable from topic navigation");
assert.ok(home.includes('href="'+updated+'"'),"Mercado card must reference canonical URL");
assert.ok(index.includes('href="'+updated+'"'),"Mercado index must link to new article");
assert.ok(sibling.includes('href="'+cat+'"'),"neighborhood article must link to parent category");
assert.ok(sibling.includes('href="'+updated+'"'),"neighborhood article must link to market new URL");
assert.ok(category.includes('href="'+article+'"'),"category must contain a real neighborhood article");
assert.ok(category.includes('href="'+updated+'"')&&category.includes('href="/regioes/lapa/"'),"category must distinguish market and commercial intent");
assert.ok(category.includes('rel="canonical" href="'+host+cat+'"'));
assert.ok(category.includes('name="robots" content="index,follow,max-image-preview:large"'));
assert.equal((category.match(/<h1\b/g)||[]).length,1);
assert.ok(css.includes("@media(max-width:480px)"),"category requires mobile-first controls");
const g=JSON.parse(category.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])["@graph"];
const page=g.find(x=>x["@type"]==="CollectionPage");
const items=g.find(x=>x["@type"]==="ItemList");
const breadcrumbs=g.find(x=>x["@type"]==="BreadcrumbList");
assert.equal(page.url,host+cat);
assert.equal(items.itemListElement.length,1,"publish only evidenced articles");
assert.equal(items.itemListElement[0].url,host+article);
assert.equal(breadcrumbs.itemListElement.at(-1).item,host+cat);
const marketSchema=JSON.parse(market.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])["@graph"];
assert.equal(marketSchema.find(x=>x["@type"]==="BlogPosting").mainEntityOfPage["@id"],host+updated);
assert.ok(market.includes('rel="canonical" href="'+host+updated+'"'));
assert.ok(market.includes('property="og:url" content="'+host+updated+'"'));
assert.ok(!market.includes(host+old),"old slug must not appear in new canonical source");
const sister=JSON.parse(sibling.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])["@graph"].find(x=>x["@type"]==="BreadcrumbList");
assert.equal(sister.itemListElement[2].item,host+cat);
assert.equal(sister.itemListElement.at(-1).position,4);
console.log(JSON.stringify({pass:true,category:host+cat,marketCanonical:host+updated,redirect301:old,categoryArticles:1,sitemapURLs:urls.length}));
